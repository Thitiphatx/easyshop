import { AuthProvider } from "@/app/contexts/authContext";
import { SettingProvider } from "@/app/contexts/settingContext";
import Footer from "@/components/Footer";
import Navbar from "@/components/Navbar";
import { checkSettingExists } from "@/app/actions/setup";
import { redirect } from "next/navigation";
import type { Metadata } from "next";
import "../globals.css";

export const metadata: Metadata = {
    title: "Create Next App",
    description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
    const hasSetting = await checkSettingExists();
    if (!hasSetting) {
        redirect("/setup");
    }

    return (
        <SettingProvider>
            <AuthProvider>
                <header className="sticky top-0 z-50 w-full">
                    <nav>
                        <Navbar />
                    </nav>
                </header>
                <main className="flex-1 w-full min-h-[calc(100vh-5rem)] flex flex-col">
                    {children}
                </main>
                <Footer />
            </AuthProvider>
        </SettingProvider>
    );
}
